// Written documentation: an ARCHITECTURE.md (overview, a Mermaid diagram, every service with its features, contracts,
// connections and evidence, the boundaries and flows) and an implementation brief for a planned change (a task list
// a coding agent such as Claude Code or Codex can work from).
import { ancestorsOf, childrenOf, subtreeNeighbours } from '../../shared/model/queries.ts'
import type { HxNode, Model } from '../../shared/model/schema.ts'
import type { Op } from '../../shared/model/ops.ts'
import type { DecisionRecord, Proposal } from '../../shared/ipc.ts'
import { decisionLogMarkdown } from '../../shared/export/adr.ts'
import { KIND_INFO } from '../../shared/model/kinds.ts'
import { connectorDataClasses, dataClassLabel, dataScope, effectiveTeam, phasesInOrder } from '../../shared/model/governance.ts'
import { mermaidFlowchart, mermaidSequences } from './formats.ts'

const ev = (n: { evidence: { path: string; lines: [number, number] | null }[] }): string =>
  n.evidence.map((e) => `\`${e.path}${e.lines !== null ? `:${e.lines[0]}` : ''}\``).join(', ')

function nodeSection(m: Model, n: HxNode, depth: number): string[] {
  const h = '#'.repeat(Math.min(6, 3 + depth))
  const out: string[] = []
  const meta = [KIND_INFO[n.kind].label, n.techStack, n.boundary === 'external' ? `external${n.vendor !== null ? ` (${n.vendor})` : ''}` : null, n.status !== 'existing' ? n.status : null].filter((x) => x !== null)
  out.push(`${h} ${n.name}`, '', `*${meta.join(' · ')}*`, '')
  const team = effectiveTeam(m, n.id)
  const teamName = team === null ? null : (m.meta.teams.find((t) => t.id === team.team)?.name ?? team.team)
  const phase = n.phase === null ? null : (m.meta.phases.find((p) => p.id === n.phase)?.name ?? n.phase)
  const facts = [
    teamName !== null ? `Team: ${teamName}${team?.inherited === true ? ' (inherited)' : ''}` : null,
    n.owner !== null ? `Owner: ${n.owner}` : null,
    n.sensitivity !== null ? `Sensitivity: ${n.sensitivity}` : null,
    n.dataClasses.length > 0 ? `Data: ${n.dataClasses.map((d) => dataClassLabel(m.meta, d)).join(', ')}` : null,
    phase !== null ? `Phase: ${phase}` : null,
  ].filter((x) => x !== null)
  if (facts.length > 0) out.push(facts.join(' · '), '')
  if (n.description.trim() !== '') out.push(n.description.trim(), '')
  if (n.notes.trim() !== '') out.push('> **Notes**', '>', ...n.notes.trim().split('\n').map((l) => `> ${l}`), '')
  if (n.features.length > 0) {
    out.push('| Feature | Protocol | Endpoint | SLA |', '|---|---|---|---|')
    for (const f of n.features) {
      const sla = f.sla === null ? '' : [f.sla.p50Ms !== null ? `p50 ${f.sla.p50Ms}ms` : '', f.sla.p99Ms !== null ? `p99 ${f.sla.p99Ms}ms` : '', f.sla.maxRps !== null ? `${f.sla.maxRps} rps` : ''].filter(Boolean).join(', ')
      out.push(`| ${f.name}${f.status !== 'existing' ? ` *(${f.status})*` : ''} | ${f.protocol ?? ''} | ${f.endpoint !== null ? `\`${f.endpoint.replace(/\|/g, '\\|')}\`` : ''} | ${sla} |`)
    }
    out.push('')
    for (const f of n.features) {
      if (f.contract === null || f.contract.body.trim() === '') continue
      const lang = f.contract.kind === 'proto' ? 'protobuf' : f.contract.kind === 'openapi' ? 'yaml' : f.contract.kind === 'json-schema' ? 'json' : f.contract.kind === 'graphql' ? 'graphql' : ''
      out.push(`**${f.name}**`, '', `\`\`\`${lang}`, f.contract.body.trim(), '```', '')
    }
  }
  const { upstream, downstream } = subtreeNeighbours(m, n.id)
  if (upstream.length > 0) out.push(`Called by: ${upstream.map((x) => x.name).join(', ')}`, '')
  if (downstream.length > 0) out.push(`Depends on: ${downstream.map((x) => x.name).join(', ')}`, '')
  if (n.evidence.length > 0) out.push(`Source: ${ev(n)}`, '')
  for (const k of childrenOf(m, n.id).sort((a, b) => a.name.localeCompare(b.name))) out.push(...nodeSection(m, k, depth + 1))
  return out
}

export function architectureMarkdown(m: Model, decisions: readonly DecisionRecord[] = []): string {
  const out: string[] = [`# ${m.meta.name}`, '']
  if (m.meta.description.trim() !== '') out.push(m.meta.description.trim(), '')
  const nodes = Object.values(m.nodes)
  out.push(`${nodes.filter((n) => n.boundary === 'internal').length} internal components, ${nodes.filter((n) => n.boundary === 'external').length} external, ${Object.keys(m.connectors).length} connections. Generated by Harpoon from \`.harpoon/project.json\`.`, '')
  out.push('## Diagram', '', '```mermaid', mermaidFlowchart(m).trimEnd(), '```', '')
  const top = childrenOf(m, null).sort((a, b) => (a.boundary === b.boundary ? a.name.localeCompare(b.name) : a.boundary === 'internal' ? -1 : 1))
  out.push('## Components', '')
  for (const n of top) out.push(...nodeSection(m, n, 0))
  out.push('## Connections', '', '| From | To | Protocol | Return | Auth | Mode |', '|---|---|---|---|---|---|')
  for (const c of Object.values(m.connectors)) {
    const name = (id: string): string => [...ancestorsOf(m, id).reverse().map((a) => a.name), m.nodes[id]?.name ?? id].join(' › ')
    out.push(`| ${name(c.source)} | ${name(c.target)} | ${c.channelA.protocol} | ${c.channelB?.protocol ?? ''} | ${c.channelA.auth ?? ''} | ${c.sync}${c.status !== 'existing' ? ` (${c.status})` : ''} |`)
  }
  out.push('')
  out.push(...governanceSections(m))
  const log = decisionLogMarkdown(decisions)
  if (log !== '') out.push(log)
  if (Object.keys(m.boundaries).length > 0) {
    out.push('## Boundaries', '')
    for (const b of Object.values(m.boundaries)) out.push(`- **${b.name}** (${b.type}): ${b.nodeIds.map((id) => m.nodes[id]?.name ?? id).join(', ')}`)
    out.push('')
  }
  const seq = mermaidSequences(m)
  if (seq !== '') {
    out.push('## Flows', '')
    for (const block of seq.trim().split('\n\n')) {
      const title = block.split('\n')[0]?.replace(/^%% /, '') ?? ''
      out.push(`### ${title}`, '', '```mermaid', block, '```', '')
    }
  }
  return `${out.join('\n')}\n`
}

/** Ownership, data in scope and the roadmap, when the project records them. */
export function governanceSections(m: Model): string[] {
  const out: string[] = []
  const nodes = Object.values(m.nodes)
  if (m.meta.teams.length > 0) {
    out.push('## Ownership', '', '| Team | Contact | Owns |', '|---|---|---|')
    for (const t of m.meta.teams) {
      const owned = nodes.filter((n) => n.team === t.id).map((n) => n.name)
      out.push(`| ${t.name} | ${t.contact ?? ''} | ${owned.join(', ')} |`)
    }
    out.push('')
  }
  const scope = dataScope(m)
  const tagged = nodes.filter((n) => scope.has(n.id))
  const carrying = Object.values(m.connectors).filter((c) => connectorDataClasses(c).length > 0)
  if (tagged.length > 0 || carrying.length > 0) {
    const label = (id: string): string => dataClassLabel(m.meta, id)
    out.push('## Data handling', '', '| Component | Data | How |', '|---|---|---|')
    for (const n of tagged.sort((a, b) => a.name.localeCompare(b.name))) {
      const byCls = scope.get(n.id)
      if (byCls === undefined) continue
      const how = [...byCls].map(([cls, r]) => `${label(cls)}: ${r.own ? 'stores/processes' : r.via.length > 0 ? 'receives or sends' : 'inside'}`).join('; ')
      out.push(`| ${n.name} | ${[...byCls.keys()].map(label).join(', ')} | ${how} |`)
    }
    out.push('')
    if (carrying.length > 0) {
      out.push('Data in transit:', '')
      for (const c of carrying) {
        const nm = (id: string): string => m.nodes[id]?.name ?? id
        out.push(`- ${nm(c.source)} → ${nm(c.target)} (${c.channelA.protocol}): ${connectorDataClasses(c).map(label).join(', ')}`)
      }
      out.push('')
    }
  }
  const phases = phasesInOrder(m.meta)
  if (phases.length > 0) {
    out.push('## Roadmap', '')
    for (const p of phases) {
      out.push(`### ${p.name}${p.target !== null ? ` (target ${p.target})` : ''} · ${p.status}`, '')
      if (p.description.trim() !== '') out.push(p.description.trim(), '')
      const items = [
        ...nodes.filter((n) => n.phase === p.id).map((n) => `- ${n.status === 'deprecated' || n.status === 'removed' ? 'Retire' : 'Add'} **${n.name}** (${KIND_INFO[n.kind].label.toLowerCase()})`),
        ...Object.values(m.connectors)
          .filter((c) => c.phase === p.id)
          .map((c) => `- Connect ${m.nodes[c.source]?.name ?? c.source} → ${m.nodes[c.target]?.name ?? c.target} (${c.channelA.protocol})`),
      ]
      out.push(...(items.length > 0 ? items : ['- Nothing assigned yet.']), '')
    }
  }
  return out
}

/** A build brief for a proposal (or any op list): what to create and change, in implementation order. */
export function implementationBrief(m: Model, p: Pick<Proposal, 'title' | 'rationale' | 'risks'> & { ops: readonly Op[] }): string {
  const added = new Map<string, HxNode>()
  for (const o of p.ops) if (o.op === 'addNode') added.set(o.node.id, o.node)
  const nm = (id: string): string => m.nodes[id]?.name ?? added.get(id)?.name ?? id
  const out: string[] = [`# Implementation brief: ${p.title}`, '']
  if (p.rationale.trim() !== '') out.push('## Why', '', p.rationale.trim(), '')
  const newNodes = p.ops.filter((o): o is Extract<Op, { op: 'addNode' }> => o.op === 'addNode')
  if (newNodes.length > 0) {
    out.push('## Build', '')
    for (const { node: n } of newNodes) {
      const where = n.parentId !== null ? ` inside **${nm(n.parentId)}**` : ''
      out.push(`- [ ] **${n.name}**: ${KIND_INFO[n.kind].label.toLowerCase()}${n.techStack !== null ? ` (${n.techStack})` : ''}${where}${n.boundary === 'external' ? `, external${n.vendor !== null ? `: integrate with ${n.vendor}` : ''}` : ''}.`)
      const facts = [
        n.team !== null ? `team ${m.meta.teams.find((t) => t.id === n.team)?.name ?? n.team}` : null,
        n.phase !== null ? `phase ${m.meta.phases.find((p) => p.id === n.phase)?.name ?? n.phase}` : null,
        n.dataClasses.length > 0 ? `handles ${n.dataClasses.map((d) => dataClassLabel(m.meta, d)).join(', ')}` : null,
      ].filter((x) => x !== null)
      if (facts.length > 0) out.push(`  *${facts.join(' · ')}*`)
      if (n.description.trim() !== '') out.push(`  ${n.description.trim().replace(/\n/g, '\n  ')}`)
      for (const f of n.features) out.push(`  - [ ] ${f.name}${f.endpoint !== null ? `: \`${f.endpoint}\`` : ''}${f.protocol !== null ? ` (${f.protocol})` : ''}`)
    }
    out.push('')
  }
  const conns = p.ops.filter((o): o is Extract<Op, { op: 'addConnector' }> => o.op === 'addConnector')
  if (conns.length > 0) {
    out.push('## Wire up', '')
    for (const { connector: c } of conns) {
      const pol = [c.policies.timeoutMs !== null ? `timeout ${c.policies.timeoutMs} ms` : '', c.policies.retries !== null ? `${c.policies.retries} retries` : '', c.policies.circuitBreaker ? 'circuit breaker' : ''].filter(Boolean).join(', ')
      out.push(`- [ ] ${nm(c.source)} → ${nm(c.target)} over **${c.channelA.protocol}**${c.sync === 'async' ? ' (async)' : ''}${c.channelA.auth !== null ? `, auth: ${c.channelA.auth}` : ''}${c.channelB !== null ? `; replies over ${c.channelB.protocol}` : ''}${pol !== '' ? `; ${pol}` : ''}${connectorDataClasses(c).length > 0 ? `; carries ${connectorDataClasses(c).map((d) => dataClassLabel(m.meta, d)).join(', ')} (encrypt in transit)` : ''}.${c.description.trim() !== '' ? ` ${c.description.trim()}` : ''}`)
    }
    out.push('')
  }
  const changes = p.ops.filter((o) => o.op === 'updateNode' || o.op === 'updateConnector')
  if (changes.length > 0) {
    out.push('## Change', '')
    for (const o of changes) {
      if (o.op === 'updateNode') out.push(`- [ ] ${nm(o.id)}: update ${Object.keys(o.patch).join(', ')}.`)
      else if (o.op === 'updateConnector') {
        const c = m.connectors[o.id]
        out.push(`- [ ] ${c !== undefined ? `${nm(c.source)} → ${nm(c.target)}` : o.id}: update ${Object.keys(o.patch).join(', ')}.`)
      }
    }
    out.push('')
  }
  const removals = p.ops.filter((o) => o.op === 'removeNode' || o.op === 'removeConnector')
  if (removals.length > 0) {
    out.push('## Retire', '')
    for (const o of removals) if (o.op === 'removeNode') out.push(`- [ ] ${nm(o.id)}`)
    out.push('')
  }
  if (p.risks !== null && p.risks.trim() !== '') out.push('## Risks', '', p.risks.trim(), '')
  const gl = m.meta.guidelines.filter((g) => g.enabled)
  if (gl.length > 0) {
    out.push('## Follow the project guidelines', '')
    for (const g of gl) out.push(`- **${g.title}**${g.text !== '' ? `: ${g.text}` : ''}`)
    out.push('')
  }
  out.push('## Done when', '', '- [ ] Every item above is implemented and covered by tests.', '- [ ] `.harpoon/project.json` statuses move from planned to existing (accept the change in Harpoon).', '')
  return `${out.join('\n')}\n`
}
