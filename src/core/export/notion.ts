// Pages for Notion: an overview (with the diagram), the architecture, the roadmap, the decision log with one page per
// decision record and, when asked, the meeting notes. As files they form a zip Notion's Markdown import turns into a
// page tree; as text they are what an AI publish run writes into the team's Notion page.
import type { DecisionRecord, NoteDoc } from '../../shared/ipc.ts'
import { adrMarkdown, adrNumber } from '../../shared/export/adr.ts'
import { phasesInOrder } from '../../shared/model/governance.ts'
import type { Model } from '../../shared/model/schema.ts'
import { architectureMarkdown, governanceSections } from './docs.ts'
import type { ZipEntry } from './zip.ts'

export interface NotionSection {
  /** Stable key (a publish run keeps the Notion page id per key). */
  key: string
  title: string
  markdown: string
}

/** A file or folder name: no separators or reserved characters, and never "." or ".." (no escaping the archive). */
const safe = (s: string): string => {
  // Control characters are dropped by code point (a regex range of them trips the linter).
  const n = [...s]
    .filter((ch) => ch.charCodeAt(0) >= 32)
    .join('')
    .replace(/[\\/:*?"<>|]+/g, '-')
    .trim()
  return n === '' || /^\.+$/.test(n) ? 'page' : n
}

export function notionSections(o: { model: Model; decisions: readonly DecisionRecord[]; notes: readonly NoteDoc[] | null; diagram: string | null; bundle: string | null; date: string }): NotionSection[] {
  const m = o.model
  const nodes = Object.values(m.nodes)
  const planned = nodes.filter((n) => n.status === 'planned' || n.status === 'in-progress').length
  const openDecisions = o.decisions.filter((d) => d.status === 'proposed').length
  const overview: string[] = [
    m.meta.description.trim() || '_No description yet._',
    '',
    `**${nodes.filter((n) => n.boundary === 'internal').length}** internal components · **${nodes.filter((n) => n.boundary === 'external').length}** external · **${Object.keys(m.connectors).length}** connections · **${planned}** planned · **${o.decisions.length}** decisions${openDecisions > 0 ? ` (${openDecisions} proposed)` : ''}`,
    '',
  ]
  if (o.diagram !== null) overview.push(`![Architecture diagram](${o.diagram})`, '')
  if (o.bundle !== null) overview.push(`The full Harpoon share bundle (interactive viewer, docs, diagram code and the project) is attached as **${o.bundle}**.`, '')
  overview.push(`_Generated by Harpoon on ${o.date}. Edit the architecture in Harpoon; this page is updated from it._`, '')

  const sections: NotionSection[] = [{ key: 'overview', title: m.meta.name, markdown: overview.join('\n') }]
  sections.push({ key: 'architecture', title: 'Architecture', markdown: architectureMarkdown(m, o.decisions).replace(/^# .*\n+/, '') })

  const gov = governanceSections(m).join('\n').trim()
  if (phasesInOrder(m.meta).length > 0 || gov !== '') sections.push({ key: 'roadmap', title: 'Roadmap, ownership and data', markdown: gov === '' ? '_Nothing recorded yet._' : gov })

  if (o.decisions.length > 0) {
    const rows = [...o.decisions].sort((a, b) => a.number - b.number).map((d) => `| ${adrNumber(d.number)} | ${d.title.replace(/\|/g, '\\|')} | ${d.status} | ${d.date} |`)
    sections.push({ key: 'decisions', title: 'Decision log', markdown: ['| # | Decision | Status | Date |', '|---|---|---|---|', ...rows, ''].join('\n') })
    for (const d of o.decisions) sections.push({ key: `adr:${d.id}`, title: `${adrNumber(d.number)} ${d.title}`, markdown: adrMarkdown(d, m, o.decisions).replace(/^# .*\n+/, '') })
  }
  if (o.notes !== null && o.notes.length > 0) {
    for (const n of o.notes) {
      const summary = n.meta.summary.trim() !== '' ? `## Summary\n\n${n.meta.summary.trim()}\n\n` : ''
      // Mentions become plain names (the harpoon: links mean nothing in Notion).
      const body = n.body.replace(/\[(@[^\]]+)\]\(harpoon:[^)]+\)/g, '**$1**')
      sections.push({ key: `note:${n.path}`, title: n.meta.title, markdown: `${summary}${body}` })
    }
  }
  return sections
}

/** The sections as a zip Notion imports (Settings → Import → Markdown & CSV): the overview page with the rest under it. */
export function notionZip(sections: readonly NotionSection[], extras: readonly ZipEntry[]): ZipEntry[] {
  const [overview, ...rest] = sections
  if (overview === undefined) return []
  const top = safe(overview.title)
  const entries: ZipEntry[] = []
  const child = (s: NotionSection): string => {
    if (s.key.startsWith('adr:')) return `${top}/Decision log/${safe(s.title)}.md`
    if (s.key.startsWith('note:')) return `${top}/Meeting notes/${safe(s.title)}.md`
    return `${top}/${safe(s.title)}.md`
  }
  // Links are relative to the linking page: the overview sits beside its folder, the rest inside it.
  const links = rest.filter((s) => !s.key.startsWith('adr:') && !s.key.startsWith('note:')).map((s) => `- [${s.title}](${encodeURI(child(s))})`)
  const notes = rest.filter((s) => s.key.startsWith('note:'))
  if (notes.length > 0) links.push(`- Meeting notes: ${notes.map((s) => `[${s.title}](${encodeURI(child(s))})`).join(', ')}`)
  entries.push({ name: `${top}.md`, data: `# ${overview.title}\n\n${overview.markdown.replace(/\]\((?!https?:)([^)]+)\)/g, (_m, p: string) => `](${encodeURI(`${top}/${p}`)})`)}\n## Pages\n\n${links.join('\n')}\n` })
  for (const s of rest) {
    let md = s.markdown
    // The decision log links to its records.
    if (s.key === 'decisions') md = `${md}\n${rest.filter((x) => x.key.startsWith('adr:')).map((x) => `- [${x.title}](${encodeURI(`Decision log/${safe(x.title)}.md`)})`).join('\n')}\n`
    entries.push({ name: child(s), data: `# ${s.title}\n\n${md}` })
  }
  for (const e of extras) entries.push({ name: `${top}/${e.name}`, data: e.data })
  return entries
}
